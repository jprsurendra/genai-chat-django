#!/usr/bin/env bash
# Regenerates THIRD_PARTY_LICENSES.md from the PRODUCTION dependencies (requirements.txt)
# plus the vendored frontend libraries. Run it after every dependency change.
#
# Uses a throw-away virtualenv so dev tools are not listed.
# Usage: scripts/generate_third_party_licenses.sh
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

VENV="$(mktemp -d)/venv"
python3 -m venv "$VENV"
"$VENV/bin/pip" install -q --disable-pip-version-check -r requirements.txt pip-licenses==5.5.5

{
  echo "# Third-Party Licenses"
  echo
  echo "GenAI Chat uses the open-source components listed below. Each is used under its own licence;"
  echo "the full licence texts are available from the linked project pages (and, for vendored frontend"
  echo "libraries, in \`static/vendor/<library>/LICENSE\`)."
  echo
  echo "_Generated by \`scripts/generate_third_party_licenses.sh\` on $(date -u +%Y-%m-%d). Do not edit by hand._"
  echo
  echo "## Frontend libraries (vendored in \`static/vendor/\`)"
  echo
  echo "| Library | Version | Licence |"
  echo "|---|---|---|"
  for dir in static/vendor/*/; do
    name="$(basename "$dir")"
    lib="${name%-*}"
    ver="${name##*-}"
    case "$lib" in
      dompurify) lic="MPL-2.0 OR Apache-2.0" ;;
      *) lic="MIT" ;;
    esac
    echo "| $lib | $ver | $lic |"
  done
  echo
  echo "## Python packages (runtime, including transitive dependencies)"
  echo
  echo "| Package | Version | Licence | Project page |"
  echo "|---|---|---|---|"
  "$VENV/bin/pip-licenses" --from=mixed --format=json --with-urls --order=name \
    --ignore-packages pip-licenses prettytable wcwidth pip setuptools |
    python3 -c '
import json, sys
for pkg in json.load(sys.stdin):
    # Some packages put the whole licence text in their metadata: keep the first line only.
    lic = pkg["License"].strip().splitlines()[0].strip()
    name, version, url = pkg["Name"], pkg["Version"], pkg["URL"]
    print(f"| {name} | {version} | {lic} | {url} |")
'
  echo
  echo "## Licence exceptions"
  echo
  echo "- **mysqlclient** (GPL-2.0-or-later): accepted for the hosted SaaS, where the software is not"
  echo "  distributed to customers. Replace it with PyMySQL (MIT) before any self-hosted / on-prem"
  echo "  distribution. Tracked in SECURITY.md."
} > THIRD_PARTY_LICENSES.md

rm -rf "$(dirname "$VENV")"
echo "Wrote THIRD_PARTY_LICENSES.md"
